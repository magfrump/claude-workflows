#!/usr/bin/env bash
# install.sh — set up the interview profile on the HOST (your WSL shell).
#
# Creates three things, all outside this repo, all idempotent:
#   ~/.claude-interview/   a separate Claude Code config dir: the slim CLAUDE.md
#                          and settings.json, both COPIED (re-run after edits).
#                          Not symlinked: other sessions switch this checkout's
#                          branch, which would make a symlinked CLAUDE.md vanish
#                          from the profile, possibly right before the call.
#   ~/interview-env/       Python venv with the interviewers' requirements.txt
#                          (+ requirements-extras.txt unless --no-extras)
#   ~/.local/bin/cci       launcher: activates the venv, points
#                          CLAUDE_CONFIG_DIR at the profile, execs `claude`
#
# Your normal ~/.claude is never read or written. The profile has no hooks,
# no plugins and none of the workflow payload.
#
# Usage: bash profiles/interview/install.sh [--no-extras] [--no-venv]
# Override locations with CCI_CONFIG_DIR, CCI_VENV, CCI_BIN.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="${CCI_CONFIG_DIR:-$HOME/.claude-interview}"
VENV="${CCI_VENV:-$HOME/interview-env}"
BIN="${CCI_BIN:-$HOME/.local/bin}"
PY_VERSION="3.12"   # torch 2.6.0 ships wheels for 3.9–3.13

extras=1 venv=1
for arg in "$@"; do
  case "$arg" in
    --no-extras) extras=0 ;;
    --no-venv)   venv=0 ;;
    -h|--help)   sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "install.sh: unknown argument: $arg" >&2; exit 2 ;;
  esac
done

# The cc-isolated container bakes this file; it has no egress, so pip and the
# Hugging Face downloads would fail there. This must run on the host.
if [ -f /etc/cc-config-hash ]; then
  echo "install.sh: this looks like the cc-isolated container. Run it from your host WSL shell." >&2
  exit 1
fi

# --- Claude Code profile ------------------------------------------------------
mkdir -p "$CONFIG_DIR"
for f in CLAUDE.md settings.json; do
  dest="$CONFIG_DIR/$f"
  [ -L "$dest" ] && rm -f "$dest"   # an older install symlinked CLAUDE.md
  # Claude Code writes runtime changes into settings.json; keep them.
  if [ -f "$dest" ] && ! cmp -s "$HERE/$f" "$dest"; then
    cp -f "$dest" "$dest.bak"
    echo "install.sh: existing $f differed; saved it as $f.bak"
  fi
  cp -f "$HERE/$f" "$dest"
done
echo "profile:  $CONFIG_DIR (CLAUDE.md, settings.json copied from $HERE)"

# --- Python venv --------------------------------------------------------------
if [ "$venv" -eq 1 ]; then
  reqs=(-r "$HERE/requirements.txt")
  [ "$extras" -eq 1 ] && reqs+=(-r "$HERE/requirements-extras.txt")

  if command -v uv >/dev/null 2>&1; then
    [ -x "$VENV/bin/python" ] || uv venv --python "$PY_VERSION" "$VENV"
    uv pip install --python "$VENV/bin/python" "${reqs[@]}"
  else
    echo "install.sh: uv not found; falling back to python3 -m venv + pip (slower)."
    [ -x "$VENV/bin/python" ] || python3 -m venv "$VENV"
    "$VENV/bin/python" -m pip install --upgrade pip
    "$VENV/bin/python" -m pip install "${reqs[@]}"
  fi
  echo "venv:     $VENV"
fi

# --- Launcher -----------------------------------------------------------------
mkdir -p "$BIN"
cat > "$BIN/cci" <<EOF
#!/usr/bin/env bash
# cci — Claude Code with the interview profile (generated by $HERE/install.sh)
[ -f "$VENV/bin/activate" ] && source "$VENV/bin/activate"
export CLAUDE_CONFIG_DIR="$CONFIG_DIR"
exec claude "\$@"
EOF
chmod +x "$BIN/cci"
echo "launcher: $BIN/cci"

case ":$PATH:" in
  *":$BIN:"*) ;;
  *) echo "note: $BIN is not on PATH; add it, or run $BIN/cci directly." ;;
esac

echo
echo "Next: bash $HERE/preflight.sh --warm   (then: mkdir -p ~/interview && cd ~/interview && cci, and /login)"
